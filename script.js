const MAX_HISTORY = 5;

function getTopicHistory() {

    const history = readSetting("topicHistory", []);

    return Array.isArray(history) ? history : [];
}


function saveTopicToHistory(topic) {

    let history = getTopicHistory();

    // Remove the topic if it already exists
    history = history.filter(function(item) {
        return item !== topic;
    });

    // Newest first, keep only the latest 5
    history.unshift(topic);
    history = history.slice(0, MAX_HISTORY);

    writeSetting("topicHistory", history);

    displayTopicHistory();
}


// Bring an old topic back onto the card
function recallTopic(topic) {

    if (isShuffling) {
        return;
    }

    showTopic(topic);

    topicCard.classList.remove("recalled");
    topicCard.offsetHeight;
    topicCard.classList.add("recalled");

    topicCard.scrollIntoView({ behavior: "smooth", block: "center" });
}


function displayTopicHistory() {

    const history = getTopicHistory();

    topicHistory.innerHTML = "";

    if (history.length === 0) {

        const emptyMessage = document.createElement("p");
        emptyMessage.className = "empty-history";
        emptyMessage.textContent = "Your recent topics will appear here.";

        topicHistory.appendChild(emptyMessage);
        return;
    }

    history.forEach(function(topic, index) {

        const item = document.createElement("button");

        item.type = "button";
        item.className = "history-item";
        item.dataset.index = String(index + 1).padStart(2, "0");
        item.textContent = topic;
        item.title = "Speak on this again";

        item.addEventListener("click", function() {
            recallTopic(topic);
        });

        topicHistory.appendChild(item);
    });
}


