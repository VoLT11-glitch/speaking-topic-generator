const timerElement = document.getElementById("timer");
const timerStatus = document.getElementById("timerStatus");
const timerButton = document.getElementById("timerBtn");
const resetButton = document.getElementById("resetBtn");
const durationButtons = document.querySelectorAll(".duration-btn");
const thinkToggle = document.getElementById("thinkToggle");
const recordToggle = document.getElementById("recordToggle");

const THINK_SECONDS = 15;

let selectedDuration = 60;      // seconds
let thinkEnabled = readSetting("thinkFirst", false);

// phase: "idle" | "think" | "speak" | "paused" | "done"
let phase = "idle";
let pausedPhase = null;         // which phase we paused in
let remainingMs = selectedDuration * 1000;
let phaseEndTime = 0;
let tickInterval = null;


// Convert milliseconds into MM:SS
function formatTime(ms) {

    const totalSeconds = Math.ceil(ms / 1000);
    const minutes = Math.floor(totalSeconds / 60);
    const seconds = totalSeconds % 60;

    return `${String(minutes).padStart(2, "0")}:${String(seconds).padStart(2, "0")}`;
}


// Update everything the timer shows, based on the current phase
function renderTimer() {

    timerElement.textContent = formatTime(remainingMs);

    const activePhase = phase === "paused" ? pausedPhase : phase;

    timerElement.classList.toggle("thinking", activePhase === "think");
    timerElement.classList.toggle("running", phase === "speak");

    const isRecording = recorder !== null && phase === "speak";
    timerStatus.classList.toggle("recording", isRecording);

    if (phase === "think") {
        timerStatus.textContent = "Think…";
    } else if (phase === "speak") {
        timerStatus.textContent = isRecording ? "Speak. Recording." : "Speak.";
    } else if (phase === "paused") {
        timerStatus.textContent = "Paused";
    } else if (phase === "done") {
        timerStatus.textContent = "Time's up.";
    } else {
        timerStatus.textContent = "";
    }

    if (phase === "think" || phase === "speak") {
        timerButton.textContent = "⏸ Pause";
    } else if (phase === "paused") {
        timerButton.textContent = "▶ Resume";
    } else {
        timerButton.textContent = "▶ Start speaking";
    }

    // Don't let settings change mid-round
    const locked = phase === "think" || phase === "speak" || phase === "paused";
    thinkToggle.disabled = locked;
    recordToggle.disabled = locked;
}


function tick() {

    remainingMs = Math.max(0, phaseEndTime - Date.now());

    if (remainingMs > 0) {
        renderTimer();
        return;
    }

    if (phase === "think") {
        playCue("start");
        beginPhase("speak", selectedDuration * 1000);
    } else {
        finishTimer();
    }
}


// Start a phase. We store the END time instead of counting down
// one second at a time, so the timer stays accurate even if the
// browser slows down background tabs.
function beginPhase(name, durationMs) {

    phase = name;
    remainingMs = durationMs;
    phaseEndTime = Date.now() + durationMs;

    if (name === "speak") {
        startRecording();
    }

    clearInterval(tickInterval);
    tickInterval = setInterval(tick, 200);

    renderTimer();
}


function startTimer() {

    unlockAudio();

    if (phase === "paused") {
        resumeTimer();
        return;
    }

    if (phase !== "idle" && phase !== "done") {
        return;
    }

    timerElement.classList.remove("done");

    if (thinkEnabled) {
        beginPhase("think", THINK_SECONDS * 1000);
    } else {
        beginPhase("speak", selectedDuration * 1000);
    }
}


function pauseTimer() {

    clearInterval(tickInterval);
    tickInterval = null;

    remainingMs = Math.max(0, phaseEndTime - Date.now());
    pausedPhase = phase;
    phase = "paused";

    pauseRecording();
    renderTimer();
}


function resumeTimer() {

    phase = pausedPhase;
    pausedPhase = null;
    phaseEndTime = Date.now() + remainingMs;

    resumeRecording();

    clearInterval(tickInterval);
    tickInterval = setInterval(tick, 200);

    renderTimer();
}


function finishTimer() {

    clearInterval(tickInterval);
    tickInterval = null;

    phase = "done";
    remainingMs = 0;

    stopRecording(true);
    playCue("end");

    timerElement.classList.remove("done");
    timerElement.offsetHeight;
    timerElement.classList.add("done");

    renderTimer();
}


function resetTimer() {

    clearInterval(tickInterval);
    tickInterval = null;

    phase = "idle";
    pausedPhase = null;

    // Reset to the selected duration
    remainingMs = selectedDuration * 1000;

    stopRecording(false);
    timerElement.classList.remove("done");

    renderTimer();
}


function toggleTimer() {

    if (phase === "think" || phase === "speak") {
        pauseTimer();
    } else {
        startTimer();
    }
}


// Select speaking duration
function selectDuration(duration) {

    // Don't change duration while the timer is counting
    if (phase === "think" || phase === "speak") {
        return;
    }

    selectedDuration = duration;

    durationButtons.forEach(function(button) {
        button.classList.toggle("active", Number(button.dataset.duration) === duration);
    });

    resetTimer();
}


durationButtons.forEach(function(button) {

    button.addEventListener("click", function() {
        selectDuration(Number(button.dataset.duration));
    });
});

timerButton.addEventListener("click", toggleTimer);
resetButton.addEventListener("click", resetTimer);


// Think-first toggle (remembered between visits)
function renderToggles() {
    thinkToggle.setAttribute("aria-pressed", String(thinkEnabled));
    recordToggle.setAttribute("aria-pressed", String(recordEnabled));
}

thinkToggle.addEventListener("click", function() {
    thinkEnabled = !thinkEnabled;
    writeSetting("thinkFirst", thinkEnabled);
    renderToggles();
});


