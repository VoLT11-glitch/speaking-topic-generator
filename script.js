const timerElement = document.getElementById("timer");
const timerButton = document.getElementById("timerBtn");
const resetButton = document.getElementById("resetBtn");
const durationButtons = document.querySelectorAll(".duration-btn");

let timeLeft = 60;
let selectedDuration = 60;
let timerInterval = null;


// Convert seconds into MM:SS
function updateTimerDisplay() {

    const minutes = Math.floor(timeLeft / 60);
    const seconds = timeLeft % 60;

    timerElement.textContent =
        `${String(minutes).padStart(2, "0")}:${String(seconds).padStart(2, "0")}`;
}


// Select speaking duration
function selectDuration(duration) {

    // Don't change duration while timer is running
    if (timerInterval !== null) {
        return;
    }

    selectedDuration = duration;
    timeLeft = duration;

    updateTimerDisplay();

    // Remove active state from all buttons
    durationButtons.forEach(function(button) {
        button.classList.remove("active");
    });

    // Add active state to selected button
    document
        .querySelector(`[data-duration="${duration}"]`)
        .classList.add("active");

    timerButton.textContent = "▶ Start speaking";
}


// Duration button clicks
durationButtons.forEach(function(button) {

    button.addEventListener("click", function() {

        const duration = Number(
            button.dataset.duration
        );

        selectDuration(duration);

    });

});


// Start the timer
function startTimer() {

    if (timerInterval !== null) {
        return;
    }

    timerElement.classList.add("running");

    timerButton.textContent = "⏸ Pause";

    timerInterval = setInterval(function() {

        timeLeft--;

        updateTimerDisplay();

        if (timeLeft <= 0) {

            clearInterval(timerInterval);

            timerInterval = null;

            timerButton.textContent = "▶ Start speaking";

            timerElement.classList.remove("running");

            timeLeft = 0;

            updateTimerDisplay();
        }

    }, 1000);
}


// Pause the timer
function pauseTimer() {

    clearInterval(timerInterval);

    timerInterval = null;

    timerButton.textContent = "▶ Resume";

    timerElement.classList.remove("running");
}


// Reset the timer
function resetTimer() {

    clearInterval(timerInterval);

    timerInterval = null;

    // Reset to the selected duration
    timeLeft = selectedDuration;

    updateTimerDisplay();

    timerButton.textContent = "▶ Start speaking";

    timerElement.classList.remove("running");
}


// Start / pause button
timerButton.addEventListener("click", function() {

    if (timerInterval === null) {

        startTimer();

    } else {

        pauseTimer();

    }

});


// Reset button
resetButton.addEventListener("click", resetTimer);


