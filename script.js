const categorySelect = document.getElementById("category");
const difficultySelect = document.getElementById("difficulty");
const topicCard = document.querySelector(".topic-card");
const topicWindow = document.querySelector(".topic-window");
const topicTrack = document.getElementById("topicTrack");
const generateButton = document.getElementById("generateBtn");
const topicHistory = document.getElementById("topicHistory");

let isShuffling = false;
let pendingShuffle = false;
let currentTopic = null;

// One "bag" per category + difficulty.
// We draw topics out of the bag until it's empty, then refill it,
// so you see all 15 before any repeats.
const topicBags = {};

function getNextTopic(category, difficulty) {

    const key = `${category}-${difficulty}`;

    if (!topicBags[key] || topicBags[key].length === 0) {

        const pool = topics[category][difficulty].filter(function(topic) {
            return topic !== currentTopic;
        });

        topicBags[key] = shuffleArray(pool);
    }

    return topicBags[key].pop();
}


// Build one <h2><span>topic</span></h2>
function createTopicElement(text) {

    const heading = document.createElement("h2");
    const inner = document.createElement("span");

    inner.textContent = text;
    heading.appendChild(inner);

    return heading;
}


// Shrink the font until the topic fits inside its slot.
// This is what stops long topics getting cut off on phones.
function fitTopic(heading) {

    const inner = heading.firstElementChild;

    if (!inner) {
        return;
    }

    heading.style.fontSize = "";

    let size = parseFloat(getComputedStyle(heading).fontSize);
    const maxHeight = heading.clientHeight - 6;

    while (inner.offsetHeight > maxHeight && size > 16) {
        size -= 1;
        heading.style.fontSize = `${size}px`;
    }
}


// The real slot height from CSS (--slot-height).
// Reading it from the page means CSS and JS can't disagree.
function getSlotHeight() {
    return topicWindow.clientHeight;
}


// Show a topic straight away, without the shuffle
function showTopic(text) {

    topicTrack.innerHTML = "";

    const heading = createTopicElement(text);
    topicTrack.appendChild(heading);

    topicTrack.style.transition = "none";
    topicTrack.style.transform = "translateY(0)";

    fitTopic(heading);

    currentTopic = text;
}


function generateTopic() {

    if (isShuffling) {
        // e.g. category changed mid-shuffle: run again once this one ends
        pendingShuffle = true;
        return;
    }

    isShuffling = true;
    generateButton.disabled = true;

    const category = categorySelect.value;
    const difficulty = difficultySelect.value;
    const availableTopics = topics[category][difficulty];

    // Choose the final topic (no repeats until the bag is empty)
    const finalTopic = getNextTopic(category, difficulty);

    // Random topics to scroll past
    const shuffleTopics = [];

    for (let i = 0; i < 10; i++) {
        const randomIndex = Math.floor(Math.random() * availableTopics.length);
        shuffleTopics.push(availableTopics[randomIndex]);
    }

    // Final topic must be the last one
    shuffleTopics.push(finalTopic);

    // Build the scrolling list
    topicTrack.innerHTML = "";

    shuffleTopics.forEach(function(topic) {
        const heading = createTopicElement(topic);
        topicTrack.appendChild(heading);
        fitTopic(heading);
    });

    // Start from the top
    topicTrack.style.transition = "none";
    topicTrack.style.transform = "translateY(0)";

    // Force browser to register the starting position
    topicTrack.offsetHeight;

    // How far to move: one slot per topic, except the last
    const finalPosition = -(shuffleTopics.length - 1) * getSlotHeight();

    topicTrack.style.transition = "transform 2.2s cubic-bezier(0.12, 0.8, 0.18, 1)";
    topicTrack.style.transform = `translateY(${finalPosition}px)`;

    // Animation finished
    setTimeout(function() {

        // Leave only the final topic in the track
        showTopic(finalTopic);
        saveTopicToHistory(finalTopic);

        isShuffling = false;
        generateButton.disabled = false;

        if (pendingShuffle) {
            pendingShuffle = false;
            generateTopic();
        }

    }, 2300);
}


generateButton.addEventListener("click", generateTopic);

// New category / difficulty → new topic from it
categorySelect.addEventListener("change", generateTopic);
difficultySelect.addEventListener("change", generateTopic);

// Re-fit the text when the screen size changes (e.g. phone rotation)
let resizeTimeout = null;

window.addEventListener("resize", function() {

    clearTimeout(resizeTimeout);

    resizeTimeout = setTimeout(function() {
        if (!isShuffling && currentTopic) {
            showTopic(currentTopic);
        }
    }, 150);
});


