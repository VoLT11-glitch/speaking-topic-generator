let audioContext = null;

// Browsers only allow sound after a tap/click, so we create the
// audio context when the user presses Start.
function unlockAudio() {

    try {
        if (!audioContext) {
            const AudioCtx = window.AudioContext || window.webkitAudioContext;
            audioContext = AudioCtx ? new AudioCtx() : null;
        }

        if (audioContext && audioContext.state === "suspended") {
            audioContext.resume();
        }
    } catch (error) {
        audioContext = null;
    }
}


function playTone(frequency, delay, duration) {

    const start = audioContext.currentTime + delay;
    const oscillator = audioContext.createOscillator();
    const gain = audioContext.createGain();

    oscillator.type = "sine";
    oscillator.frequency.value = frequency;

    gain.gain.setValueAtTime(0.0001, start);
    gain.gain.exponentialRampToValueAtTime(0.18, start + 0.02);
    gain.gain.exponentialRampToValueAtTime(0.0001, start + duration);

    oscillator.connect(gain);
    gain.connect(audioContext.destination);

    oscillator.start(start);
    oscillator.stop(start + duration + 0.05);
}


// "start" = soft single tone (think → speak)
// "end"   = two gentle tones (time's up)
function playCue(type) {

    if (audioContext) {
        try {
            if (type === "start") {
                playTone(660, 0, 0.3);
            } else {
                playTone(880, 0, 0.4);
                playTone(660, 0.2, 0.6);
            }
        } catch (error) {
            // Sound is a nice-to-have
        }
    }

    if (navigator.vibrate) {
        navigator.vibrate(type === "start" ? 60 : [120, 80, 120]);
    }
}


// =========================
// RECORDING
// Uses the browser's MediaRecorder — nothing is uploaded anywhere.
// =========================

const playback = document.getElementById("playback");
const playbackAudio = document.getElementById("playbackAudio");
const downloadLink = document.getElementById("downloadLink");

const canRecord = Boolean(
    navigator.mediaDevices &&
    navigator.mediaDevices.getUserMedia &&
    window.MediaRecorder
);

let recordEnabled = false;      // not remembered: mic is opt-in every visit
let recorder = null;
let micStream = null;
let recordingUrl = null;

if (!canRecord) {
    recordToggle.hidden = true;
}


function releaseMic() {

    if (micStream) {
        micStream.getTracks().forEach(function(track) {
            track.stop();
        });
    }

    micStream = null;
}


function clearPlayback() {

    if (recordingUrl) {
        URL.revokeObjectURL(recordingUrl);
    }

    recordingUrl = null;
    playbackAudio.removeAttribute("src");
    playback.hidden = true;
}


function showStatusNote(text) {
    timerStatus.classList.remove("recording");
    timerStatus.textContent = text;
}


// Turning recording on asks for mic permission straight away,
// so the permission popup doesn't appear mid-sentence later.
recordToggle.addEventListener("click", async function() {

    if (recordEnabled) {
        recordEnabled = false;
        renderToggles();
        return;
    }

    try {
        const stream = await navigator.mediaDevices.getUserMedia({ audio: true });

        // We only needed permission — close the mic until you speak
        stream.getTracks().forEach(function(track) {
            track.stop();
        });

        recordEnabled = true;
        renderToggles();

    } catch (error) {
        showStatusNote("Mic blocked. Allow it in your browser to record.");
    }
});


async function startRecording() {

    if (!recordEnabled || !canRecord) {
        return;
    }

    clearPlayback();

    try {
        const stream = await navigator.mediaDevices.getUserMedia({ audio: true });

        // The round might have been reset while we waited for the mic
        const stillSpeaking =
            phase === "speak" ||
            (phase === "paused" && pausedPhase === "speak");

        if (!stillSpeaking) {
            stream.getTracks().forEach(function(track) {
                track.stop();
            });
            return;
        }

        micStream = stream;

        const chunks = [];
        const thisRecorder = new MediaRecorder(stream);

        thisRecorder.ondataavailable = function(event) {
            if (event.data && event.data.size > 0) {
                chunks.push(event.data);
            }
        };

        thisRecorder.onstop = function() {

            releaseMic();

            if (thisRecorder.keepResult && chunks.length > 0) {

                const type = thisRecorder.mimeType || "audio/webm";
                const blob = new Blob(chunks, { type: type });
                const extension = type.includes("mp4") ? "m4a" : "webm";

                recordingUrl = URL.createObjectURL(blob);
                playbackAudio.src = recordingUrl;
                downloadLink.href = recordingUrl;
                downloadLink.download = `speak-recording.${extension}`;
                playback.hidden = false;
            }
        };

        recorder = thisRecorder;
        recorder.start();

        if (phase === "paused") {
            recorder.pause();
        }

        renderTimer();

    } catch (error) {
        showStatusNote("Couldn't start the mic. Recording skipped.");
    }
}


function pauseRecording() {
    if (recorder && recorder.state === "recording") {
        recorder.pause();
    }
}


function resumeRecording() {
    if (recorder && recorder.state === "paused") {
        recorder.resume();
    }
}


// keep = true  → show the recording for playback
// keep = false → throw it away (Reset)
function stopRecording(keep) {

    if (recorder) {

        recorder.keepResult = keep;

        if (recorder.state !== "inactive") {
            recorder.stop();
        }

        recorder = null;
    }

    if (!keep) {
        clearPlayback();
    }
}


// =========================
// KEYBOARD SHORTCUTS
// Space = new topic, T = start / pause, R = reset
// =========================

document.addEventListener("keydown", function(event) {

    if (event.ctrlKey || event.metaKey || event.altKey) {
        return;
    }

    // Let buttons, dropdowns and the audio player handle their own keys
    const tag = event.target.tagName;

    if (["SELECT", "INPUT", "TEXTAREA", "BUTTON", "AUDIO", "A"].includes(tag)) {
        return;
    }

    const key = event.key.toLowerCase();

    if (key === " ") {
        event.preventDefault();
        generateTopic();
    } else if (key === "t") {
        toggleTimer();
    } else if (key === "r") {
        resetTimer();
    }
});


